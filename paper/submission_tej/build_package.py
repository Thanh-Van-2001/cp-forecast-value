"""Build the Electricity Journal submission package from paper/main.tex:
a single self-contained manuscript.tex (macros and bibliography inlined), the figures,
a compiled manuscript.pdf for checking, and cover letter / highlights as .docx.
Run from the repository root: python -I paper/submission_tej/build_package.py"""
import os
import shutil
import subprocess

P = "paper"
OUT = os.path.join(P, "submission_tej", "package")
os.makedirs(OUT, exist_ok=True)
src = open(os.path.join(P, "main.tex"), encoding="utf-8").read()
macros = open(os.path.join(P, "macros.tex"), encoding="utf-8").read()
bbl = open(os.path.join(P, "main.bbl"), encoding="utf-8").read()
assert src.count("\\input{macros}") == 1 and src.count("\\bibliography{refs}") == 1
src = src.replace("\\input{macros}", "% --- result macros (generated by code/make_macros.py) ---\n" + macros.strip() + "\n% --- end macros ---")
src = src.replace("\\bibliographystyle{elsarticle-harv}\n\\bibliography{refs}", bbl.strip())
assert "\\bibliography{" not in src
open(os.path.join(OUT, "manuscript.tex"), "w", encoding="utf-8").write(src)
for f in ("fig_capture_mae.pdf", "fig_error_types.pdf", "fig_pjm_offset.pdf"):
    shutil.copy(os.path.join(P, f), os.path.join(OUT, f))
for _ in range(2):
    subprocess.run(["pdflatex", "-interaction=nonstopmode", "manuscript.tex"], cwd=OUT, stdout=subprocess.DEVNULL, check=False)
for ext in ("aux", "log", "out", "spl"):
    p = os.path.join(OUT, "manuscript." + ext)
    if os.path.exists(p):
        os.remove(p)
hl = [h.strip() for h in open(os.path.join(P, "submission_tej", "highlights.txt"), encoding="utf-8") if h.strip()]
assert 3 <= len(hl) <= 5 and all(len(h) <= 85 for h in hl)
hl_md = os.path.join(OUT, "_highlights.md")
open(hl_md, "w", encoding="utf-8").write("Highlights\n\n" + "\n".join("- " + h for h in hl) + "\n")
subprocess.run(["pandoc", hl_md, "-f", "markdown", "-o", os.path.join(OUT, "highlights.docx")], check=True)
os.remove(hl_md)
subprocess.run(["pandoc", os.path.join(P, "submission_tej", "cover_letter.md"), "-f", "markdown",
                "-o", os.path.join(OUT, "cover_letter.docx")], check=True)
print(sorted(os.listdir(OUT)))
